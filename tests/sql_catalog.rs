//! `schema/current-functions.sql` is the readable, current definition of
//! every WMS database function and trigger after all migrations. Later
//! migrations often redefine earlier functions, so this file is the single
//! place to read the rule in force. This test fails when the migrations and
//! the file disagree. Regenerate with:
//!
//!   WMS_UPDATE_SQL_CATALOG=1 bash scripts/local-postgres.sh \
//!     cargo test --locked --test sql_catalog -- --ignored
//!
//! Function bodies are PostgreSQL's stored source text, which is the same on
//! every server version; formatting comes from this test, not the server.
use stateset_warehouse::store::Store;
use std::fmt::Write;

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/schema/current-functions.sql");

async fn catalog(store: &Store) -> String {
    let functions: Vec<(String, String, String, String, String, String)> = sqlx::query_as(
        "SELECT p.proname, pg_get_function_identity_arguments(p.oid), pg_get_function_result(p.oid),
                l.lanname, CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
                p.prosrc
         FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace JOIN pg_language l ON l.oid=p.prolang
         WHERE n.nspname='public' AND p.proname LIKE 'wms\\_%'
         ORDER BY p.proname, pg_get_function_identity_arguments(p.oid)",
    )
    .fetch_all(&store.pool)
    .await
    .expect("current WMS functions");
    let triggers: Vec<(String, String, bool, String)> = sqlx::query_as(
        "SELECT c.relname, t.tgname, t.tgconstraint<>0, p.proname
         FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
         JOIN pg_proc p ON p.oid=t.tgfoid
         WHERE n.nspname='public' AND NOT t.tgisinternal AND c.relname LIKE 'wms\\_%'
         ORDER BY c.relname, t.tgname",
    )
    .fetch_all(&store.pool)
    .await
    .expect("current WMS triggers");
    let mut out = String::from(
        "-- GENERATED by tests/sql_catalog.rs from a freshly migrated database.\n\
         -- The current definition of every WMS function and trigger, after all\n\
         -- migrations. Read here; change only through a new migration, then\n\
         -- regenerate (see the test's header). Do not apply this file.\n\n\
         -- Triggers: table | trigger | deferred constraint | function\n",
    );
    for (table, name, constraint, function) in &triggers {
        let kind = if *constraint { "deferred" } else { "immediate" };
        writeln!(out, "--   {table} | {name} | {kind} | {function}").expect("write");
    }
    writeln!(out, "\n-- {} functions\n", functions.len()).expect("write");
    for (name, args, result, language, volatility, body) in functions {
        writeln!(
            out,
            "-- ------------------------------------------------------------------\n\
             -- {name}({args}) RETURNS {result}\n\
             -- LANGUAGE {language} {volatility}\n\
             {}\n",
            body.trim_matches('\n')
        )
        .expect("write");
    }
    out
}

#[tokio::test]
#[ignore = "requires isolated PostgreSQL"]
async fn current_function_catalog_matches_the_migrations() {
    use sqlx::{postgres::PgConnectOptions, Connection};
    // Migrate a fresh owned database, so fixtures other tests create in the
    // shared test database can never appear in the catalog.
    let url = std::env::var("WMS_TEST_DATABASE_URL").expect("isolated PostgreSQL test URL");
    let mut target = reqwest::Url::parse(&url).expect("test database URI");
    assert!(target.path().contains("test"));
    let name = format!("wms_sql_catalog_test_{}", std::process::id());
    let options: PgConnectOptions = url.parse().expect("test server options");
    let mut admin = sqlx::PgConnection::connect_with(&options.database("postgres"))
        .await
        .expect("owned test database administrator");
    sqlx::query(&format!("DROP DATABASE IF EXISTS {name}"))
        .execute(&mut admin)
        .await
        .expect("remove a stale catalog database");
    sqlx::query(&format!(
        "CREATE DATABASE {name} TEMPLATE template0 ENCODING 'UTF8'"
    ))
    .execute(&mut admin)
    .await
    .expect("fresh owned database");
    target.set_path(&format!("/{name}"));
    let store = Store::connect(target.as_str())
        .await
        .expect("current migrations");
    let actual = catalog(&store).await;
    store.pool.close().await;
    sqlx::query("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname=$1 AND pid<>pg_backend_pid()")
        .bind(&name)
        .execute(&mut admin)
        .await
        .expect("end leftover sessions on the owned database");
    sqlx::query(&format!("DROP DATABASE {name}"))
        .execute(&mut admin)
        .await
        .expect("remove owned database");
    if std::env::var("WMS_UPDATE_SQL_CATALOG").as_deref() == Ok("1") {
        std::fs::write(PATH, &actual).expect("write schema/current-functions.sql");
        return;
    }
    let recorded = std::fs::read_to_string(PATH).unwrap_or_default();
    if recorded != actual {
        let first = recorded
            .lines()
            .zip(actual.lines())
            .position(|(a, b)| a != b)
            .unwrap_or_else(|| recorded.lines().count().min(actual.lines().count()));
        panic!(
            "schema/current-functions.sql is stale (first difference at line {}). \
             Regenerate it with WMS_UPDATE_SQL_CATALOG=1 (see tests/sql_catalog.rs).",
            first + 1
        );
    }
}
